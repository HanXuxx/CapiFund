"""业务层依赖的数据访问契约，不含 SQLite 或文件路径。"""
from __future__ import annotations
from contextlib import AbstractContextManager
from dataclasses import dataclass
from typing import Any, Protocol


@dataclass(frozen=True)
class RecordHead:
    id: str
    author_id: str
    revision: int
    type: str
    topic_id: str | None = None
    reply_to_id: str | None = None
    floor: int | None = None


class Session(Protocol):
    def protocol(self) -> dict[str, Any]: ...
    def head(self, record_id: str) -> RecordHead | None: ...
    # 主题内回复按楼层升序分页，返回 items（RecordHead）与 total。
    def topic_replies(self, topic_id: str, page: int, page_size: int) -> dict[str, Any]: ...
    def find_records(self, filters: dict[str, Any], sort: str | None, page: int, page_size: int) -> dict[str, Any]: ...
    def tag_counts(self) -> dict[str, int]: ...
    def version(self, record_id: str, revision: int) -> dict[str, Any] | None: ...
    def body(self, record_id: str, revision: int) -> str: ...
    def history(self, record_id: str, page: int, page_size: int) -> list[dict[str, Any]]: ...
    def request(self, editor_id: str, request_id: str) -> dict[str, Any] | None: ...
    def next_floor(self, topic_id: str) -> int: ...
    def insert(self, head: RecordHead, metadata: dict[str, Any]) -> None: ...
    def append(self, record_id: str, revision: int, metadata: dict[str, Any], body: str,
               editor: dict[str, Any], request_id: str, fingerprint: str, operation: str) -> None: ...
    # 未结逻辑下 pending 且 due_date 不晚于 cutoff 的验证节点，按到期日升序；最多返回 limit 条。
    def due_checkpoints(self, cutoff: str, limit: int) -> dict[str, Any]: ...
    # active 逻辑中晚于主帖最近修订的证据回复，按最新证据时间倒序；最多返回 limit 条。
    def theses_with_new_evidence(self, limit: int) -> dict[str, Any]: ...


class FundStorage(Protocol):
    def transaction(self, *, write: bool = False) -> AbstractContextManager[Session]: ...
